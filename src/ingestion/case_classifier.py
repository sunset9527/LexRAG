"""不依赖 LLM 的年度案例案由初分规则。"""


class RuleBasedCaseCauseClassifier:
    """只在文本存在明确关键词时归类，否则交由人工校验。"""

    _rules = {
        "labor": (
            ("确认劳动关系纠纷", ("劳动关系", "确认劳动关系")),
            ("劳动报酬纠纷", ("劳动报酬", "拖欠工资", "工资")),
            ("经济补偿金纠纷", ("经济补偿", "补偿金")),
            ("工伤保险待遇纠纷", ("工伤", "工伤保险待遇")),
            ("竞业限制纠纷", ("竞业限制", "竞业")),
        ),
        "company": (
            ("公司决议纠纷", ("公司决议", "股东会决议", "董事会决议")),
            ("股东资格确认纠纷", ("股东资格", "确认股东资格")),
            ("股权转让纠纷", ("股权转让",)),
            ("损害公司利益责任纠纷", ("损害公司利益",)),
        ),
        "intellectual_property": (
            ("侵害商标权纠纷", ("商标权", "注册商标")),
            ("侵害著作权纠纷", ("著作权", "版权")),
            ("侵害发明专利权纠纷", ("发明专利", "专利权")),
            ("不正当竞争纠纷", ("不正当竞争",)),
        ),
        "criminal": (
            ("危险驾驶罪", ("危险驾驶", "醉酒驾驶")),
            ("盗窃罪", ("盗窃",)),
            ("诈骗罪", ("诈骗",)),
            ("故意伤害罪", ("故意伤害",)),
        ),
    }

    def __init__(self, *, domain: str):
        self._domain = domain

    def classify(self, text: str) -> str:
        for case_cause, keywords in self._rules.get(self._domain, ()):
            if any(keyword in text for keyword in keywords):
                return case_cause
        return "未分类（待人工校验）"
